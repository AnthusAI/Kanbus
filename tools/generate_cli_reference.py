#!/usr/bin/env python3
"""Generate the complete command index in docs/CLI_REFERENCE.md.

The index is derived from the click command tree so every command and option
the CLI accepts is documented, and a stale document fails CI.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import click

REPOSITORY_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPOSITORY_ROOT / "python" / "src"))

from kanbus.cli import cli

CLI_REFERENCE_DOCUMENT_PATH = REPOSITORY_ROOT / "docs" / "CLI_REFERENCE.md"
BEGIN_MARKER = "<!-- BEGIN GENERATED: command-index -->"
END_MARKER = "<!-- END GENERATED: command-index -->"
PROGRAM_NAME = "kanbus"


def walk_commands(command: click.Command, path: list[str]):
    yield path, command
    if isinstance(command, click.Group):
        context = click.Context(command)
        for name in command.list_commands(context):
            child = command.get_command(context, name)
            if child is not None and not child.hidden:
                yield from walk_commands(child, path + [name])


def describe_option(parameter: click.Parameter) -> str:
    if isinstance(parameter, click.Option):
        names = ", ".join(
            f"`{name}`" for name in parameter.opts + parameter.secondary_opts
        )
        placeholder = (
            ""
            if parameter.is_flag
            else f" `{parameter.make_metavar(click.Context(click.Command('x')))}`"
        )
        description = (parameter.help or "").replace("\n", " ").replace("|", "\\|")
        default = parameter.default
        default_note = (
            f" Default: `{default}`."
            if default not in (None, False, (), "")
            and not parameter.is_flag
            and type(default).__name__ != "Sentinel"
            else ""
        )
        entry = f"- {names}{placeholder}"
        if description:
            entry += f": {description}"
        return f"{entry}{default_note}"
    metavar = parameter.make_metavar(click.Context(click.Command("x")))
    return f"- `{metavar}` (argument)"


def render_command(path: list[str], command: click.Command) -> str:
    heading_level = "#" * min(1 + len(path), 6)
    invocation = " ".join(path)
    lines = [f"{heading_level} `{invocation}`", ""]
    help_text = (command.help or "").strip()
    if help_text:
        lines.extend([help_text.split("\n\n")[0].replace("\n", " "), ""])
    if not isinstance(command, click.Group):
        parameters = [
            parameter
            for parameter in command.params
            if not getattr(parameter, "hidden", False)
        ]
        for parameter in parameters:
            lines.append(describe_option(parameter))
        if parameters:
            lines.append("")
    return "\n".join(lines)


def render_generated_block() -> str:
    sections = [
        render_command(path, command)
        for path, command in walk_commands(cli, [PROGRAM_NAME])
        if len(path) > 1
    ]
    generated_notice = (
        "<!-- Generated by tools/generate_cli_reference.py; do not edit by hand. -->"
    )
    body = "\n".join(sections).rstrip()
    return f"{BEGIN_MARKER}\n{generated_notice}\n\n{body}\n{END_MARKER}"


def replace_generated_block(document_text: str) -> str:
    pattern = re.compile(
        re.escape(BEGIN_MARKER) + r".*?" + re.escape(END_MARKER), re.DOTALL
    )
    if not pattern.search(document_text):
        raise SystemExit(
            f"{CLI_REFERENCE_DOCUMENT_PATH} is missing the generated block markers"
        )
    return pattern.sub(lambda _match: render_generated_block(), document_text)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if the document is stale"
    )
    arguments = parser.parse_args()

    current_text = CLI_REFERENCE_DOCUMENT_PATH.read_text()
    regenerated_text = replace_generated_block(current_text)
    if arguments.check:
        if regenerated_text != current_text:
            print(
                "docs/CLI_REFERENCE.md is stale; run python tools/generate_cli_reference.py",
                file=sys.stderr,
            )
            return 1
        return 0
    CLI_REFERENCE_DOCUMENT_PATH.write_text(regenerated_text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
