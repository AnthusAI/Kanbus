#!/usr/bin/env python3
"""Generate the project configuration field reference in docs/CONFIGURATION.md.

The field table is derived from the ProjectConfiguration model so the document
cannot drift from the schema the loader enforces.
"""

from __future__ import annotations

import argparse
import re
import sys
import tempfile
from pathlib import Path

import yaml

REPOSITORY_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPOSITORY_ROOT / "python" / "src"))

from pydantic_core import PydanticUndefined

from kanbus.config_loader import ConfigurationError, load_project_configuration
from kanbus.models import ProjectConfiguration

CONFIGURATION_DOCUMENT_PATH = REPOSITORY_ROOT / "docs" / "CONFIGURATION.md"
BEGIN_MARKER = "<!-- BEGIN GENERATED: project-configuration-fields -->"
END_MARKER = "<!-- END GENERATED: project-configuration-fields -->"


def describe_annotation(annotation: object) -> str:
    rendered = (
        annotation.__name__
        if isinstance(annotation, type)
        else str(annotation).replace("typing.", "")
    )
    return re.sub(r"kanbus\.models\.", "", rendered).replace("NoneType", "None")


def describe_default(field_information) -> str:
    if field_information.is_required():
        return "required"
    if field_information.default_factory is not None:
        produced = field_information.default_factory()
        if hasattr(produced, "model_dump"):
            return "see section"
        return f"`{produced!r}`"
    if field_information.default is PydanticUndefined:
        return "required"
    return f"`{field_information.default!r}`"


def extract_parameter_descriptions(docstring: str) -> dict[str, str]:
    descriptions: dict[str, str] = {}
    for match in re.finditer(r"^\s*:param (\w+): (.+)$", docstring, re.MULTILINE):
        descriptions[match.group(1)] = match.group(2).strip()
    return descriptions


def build_field_table() -> str:
    descriptions = extract_parameter_descriptions(ProjectConfiguration.__doc__ or "")
    rows = ["| Key | Type | Default | Description |", "| --- | --- | --- | --- |"]
    for field_name, field_information in ProjectConfiguration.model_fields.items():
        description = descriptions.get(field_name)
        if description is None:
            raise SystemExit(
                f"ProjectConfiguration.{field_name} has no ':param' entry in its docstring"
            )
        type_text = describe_annotation(field_information.annotation).replace(
            "|", "\\|"
        )
        rows.append(
            f"| `{field_name}` | `{type_text}` | {describe_default(field_information)} | {description} |"
        )
    return "\n".join(rows)


def render_generated_block() -> str:
    generated_notice = (
        "<!-- Generated by tools/generate_configuration_reference.py; "
        "do not edit by hand. -->"
    )
    return f"{BEGIN_MARKER}\n{generated_notice}\n{build_field_table()}\n{END_MARKER}"


def replace_generated_block(document_text: str) -> str:
    pattern = re.compile(
        re.escape(BEGIN_MARKER) + r".*?" + re.escape(END_MARKER), re.DOTALL
    )
    if not pattern.search(document_text):
        raise SystemExit(
            f"{CONFIGURATION_DOCUMENT_PATH} is missing the generated block markers"
        )
    return pattern.sub(lambda _match: render_generated_block(), document_text)


YAML_BLOCK_PATTERN = re.compile(r"```yaml\n(.*?)```", re.DOTALL)


def looks_like_configuration(parsed_block: object) -> bool:
    """Return True when a parsed YAML block uses ProjectConfiguration keys.

    Blocks that share no key with the configuration model (for example a
    data sample) are not configuration files and are not validated.
    """
    if not isinstance(parsed_block, dict):
        return False
    known_keys = set(ProjectConfiguration.model_fields)
    return any(key in known_keys for key in parsed_block)


def validate_documented_yaml_blocks(document_text: str) -> list[str]:
    """Validate every configuration-shaped yaml block with the real loader.

    Each block is written to a temporary .kanbus.yml and loaded through
    ``load_project_configuration``, the same path ``kanbus`` uses, so unknown
    keys and invalid values fail exactly as they would for a reader who copies
    the block. Returns one message per failing block, quoting the block.
    """
    failures: list[str] = []
    for match in YAML_BLOCK_PATTERN.finditer(document_text):
        block_text = match.group(1)
        try:
            parsed_block = yaml.safe_load(block_text)
        except yaml.YAMLError as error:
            failures.append(f"unparseable yaml block:\n{block_text}\n{error}")
            continue
        if not looks_like_configuration(parsed_block):
            continue
        with tempfile.TemporaryDirectory() as temporary_directory:
            configuration_path = Path(temporary_directory) / ".kanbus.yml"
            configuration_path.write_text(block_text)
            try:
                load_project_configuration(configuration_path)
            except ConfigurationError as error:
                failures.append(f"invalid configuration block:\n{block_text}\n{error}")
    return failures


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if the document is stale"
    )
    arguments = parser.parse_args()

    current_text = CONFIGURATION_DOCUMENT_PATH.read_text()
    regenerated_text = replace_generated_block(current_text)
    if arguments.check:
        if regenerated_text != current_text:
            print(
                "docs/CONFIGURATION.md is stale; run python tools/generate_configuration_reference.py",
                file=sys.stderr,
            )
            return 1
        block_failures = validate_documented_yaml_blocks(current_text)
        for failure in block_failures:
            print(failure, file=sys.stderr)
        return 1 if block_failures else 0
    CONFIGURATION_DOCUMENT_PATH.write_text(regenerated_text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
